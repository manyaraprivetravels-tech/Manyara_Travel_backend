

from datetime import datetime
from enum import Enum
from typing import Literal, Optional

from pydantic import BaseModel, ConfigDict, Field, field_validator

# ============================================================
# STATUS
# ============================================================


class StatusEnum(str, Enum):
    draft = "draft"
    published = "published"


RegionLiteral = Literal["domestic", "international"]


# ============================================================
# IMAGE OBJECT
# ============================================================


class ImageObject(BaseModel):
    url: str
    public_id: Optional[str] = None


# ============================================================
# SHARED PACKAGE FIELDS
# ============================================================


class PackageFieldsMixin(BaseModel):
    """
    The package a review is about. All optional so old clients
    (and old rows) keep working; `destination` stays required.
    """

    package_id: Optional[int] = Field(default=None, ge=1)

    package_slug: Optional[str] = Field(default=None, max_length=255)

    package_title: Optional[str] = Field(default=None, max_length=255)

    package_type: Optional[str] = Field(default=None, max_length=100)

    region: Optional[RegionLiteral] = None

    @field_validator("package_slug", "package_title", "package_type", mode="before")
    @classmethod
    def _blank_to_none(cls, value):
        if isinstance(value, str):
            value = value.strip()
            return value or None
        return value

    @field_validator("region", mode="before")
    @classmethod
    def _normalize_region(cls, value):
        if isinstance(value, str):
            value = value.strip().lower()
            return value or None
        return value


# ============================================================
# PUBLIC REVIEW SUBMISSION
# ============================================================


class TestimonialPublicCreate(PackageFieldsMixin):
    """
    Used when a visitor submits a review from the public website.

    The visitor cannot control:
    - slug
    - status
    - display_order
    - created_by
    """

    customer_name: str = Field(min_length=2, max_length=100)

    customer_city: str = Field(min_length=2, max_length=100)

    destination: str = Field(min_length=2, max_length=150)

    rating: int = Field(ge=1, le=5)

    review: str = Field(min_length=10, max_length=3000)

    image: Optional[ImageObject] = None


# ============================================================
# ADMIN CREATE
# ============================================================


class TestimonialCreate(PackageFieldsMixin):
    """
    Used by admin/creator when creating a testimonial.

    The slug is generated by the backend.
    """

    customer_name: str = Field(min_length=2, max_length=100)

    customer_city: str = Field(min_length=2, max_length=100)

    destination: str = Field(min_length=2, max_length=150)

    rating: int = Field(ge=1, le=5)

    review: str = Field(min_length=10, max_length=3000)

    image: Optional[ImageObject] = None

    display_order: int = Field(default=0, ge=0)

    status: StatusEnum = StatusEnum.draft


# ============================================================
# ADMIN UPDATE
# ============================================================


class TestimonialUpdate(PackageFieldsMixin):
    """
    Used by admin/creator to edit an existing testimonial.

    The slug is intentionally not accepted here.

    Once a review has a public URL, keeping the slug stable
    prevents existing links from breaking when the customer
    name or destination is edited.
    """

    customer_name: Optional[str] = Field(default=None, min_length=2, max_length=100)

    customer_city: Optional[str] = Field(default=None, min_length=2, max_length=100)

    destination: Optional[str] = Field(default=None, min_length=2, max_length=150)

    rating: Optional[int] = Field(default=None, ge=1, le=5)

    review: Optional[str] = Field(default=None, min_length=10, max_length=3000)

    image: Optional[ImageObject] = None

    display_order: Optional[int] = Field(default=None, ge=0)

    status: Optional[StatusEnum] = None


# ============================================================
# RESPONSE
# ============================================================


class TestimonialOut(BaseModel):
    """
    Public/admin testimonial response.

    Includes the backend-generated SEO-friendly slug.
    """

    model_config = ConfigDict(from_attributes=True)

    id: int

    customer_name: str

    customer_city: str

    destination: str

    package_id: Optional[int] = None

    package_slug: Optional[str] = None

    package_title: Optional[str] = None

    package_type: Optional[str] = None

    region: Optional[str] = None

    slug: str

    rating: int

    review: str

    image: Optional[ImageObject] = None

    display_order: int

    status: StatusEnum

    created_by: Optional[int] = None

    created_at: Optional[datetime] = None

    updated_at: Optional[datetime] = None















































